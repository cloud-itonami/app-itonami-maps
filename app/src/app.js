// ── navigation (computed on this device) ─────────────────────────────────────
const roadSource = createRoadSource({ op: roadsOperation(candidates), selector: operations.roads, invoke: port.invoke, store });
const fmtKm = (m) => (m >= 10000 ? `${Math.round(m / 1000).toLocaleString("ja-JP")} km` : `${(m / 1000).toFixed(1)} km`);
const fmtTime = (s) => { const h = Math.floor(s / 3600), m = Math.round((s % 3600) / 60); return h ? `${h} 時間 ${m} 分` : `${m} 分`; };
const KIND_JA = { "Major Highway": "幹線道路", Beltway: "環状道路", Bypass: "バイパス", "Secondary Highway": "主要道路", Road: "道路", Unknown: "道路", Track: "未舗装路", "Ferry Route": "フェリー", "Ferry, seasonal": "フェリー（季節運航）" };
const roadStatus = (text, error = false) => { const el = $("roads-status"); el.textContent = text; el.classList.toggle("error", error); };
const placeLabel = (p) => (p.ja ? `${p.ja}（${p.country}）` : `${p.name}（${p.country}）`);

function setEnd(which, point) {
  ends[which] = point;
  $(which).value = point?.label ?? "";
  setPicking(null);
  routePath = null; $("route-result").replaceChildren();
  invalidate();
}
function setPicking(which) {
  picking = which;
  for (const w of ["from", "to"]) $(`${w}-pick`).setAttribute("aria-pressed", String(picking === w));
  canvas.style.cursor = picking ? "crosshair" : "";
}
for (const which of ["from", "to"]) {
  const input = $(which), list = $(`${which}-results`);
  let found = [], cursor = -1;
  const show = () => {
    list.replaceChildren(...found.map((p, i) => {
      const li = document.createElement("li");
      li.setAttribute("role", "option"); li.setAttribute("aria-selected", String(i === cursor)); li.textContent = placeLabel(p);
      li.addEventListener("pointerdown", (e) => { e.preventDefault(); pick(p); });
      return li;
    }));
    list.hidden = found.length === 0;
  };
  const pick = (p) => { found = []; show(); setEnd(which, { lon: p.lon, lat: p.lat, label: placeLabel(p) }); };
  input.addEventListener("input", () => { found = searchPlaces(places, input.value, 6); cursor = found.length ? 0 : -1; show(); });
  input.addEventListener("keydown", (e) => {
    if ((e.key === "ArrowDown" || e.key === "ArrowUp") && found.length) { e.preventDefault(); cursor = (cursor + (e.key === "ArrowDown" ? 1 : found.length - 1)) % found.length; show(); }
    else if (e.key === "Enter" && found[cursor]) { e.preventDefault(); pick(found[cursor]); }
    else if (e.key === "Escape") { found = []; show(); }
  });
  input.addEventListener("blur", () => { found = []; show(); });
  $(`${which}-pick`).addEventListener("click", () => setPicking(picking === which ? null : which));
}

function showRoute(result) {
  const box = $("route-result");
  box.replaceChildren();
  const p = (text, cls) => { const el = document.createElement("p"); el.textContent = text; if (cls) el.className = cls; return el; };
  if (result.error) {
    const why = { "no-road-near-start": "出発地の近く（50 km 以内）に道路データがありません。", "no-road-near-end": "目的地の近く（50 km 以内）に道路データがありません。", "same-place": "出発地と目的地が同じ地点です。", "not-connected": "道路でつながっていません（海を越える場合はフェリーの有無によります）。" }[result.error];
    box.append(p(why ?? result.error, "error"));
    routePath = null; invalidate();
    return;
  }
  routePath = buildRoutePath([[ends.from.lon, ends.from.lat], ...result.coords, [ends.to.lon, ends.to.lat]]);
  box.append(p(`${fmtKm(result.meters)}・約 ${fmtTime(result.seconds)}`, "summary"));
  box.append(p("時間は道路の種類ごとの想定速度による目安です。渋滞・信号・休憩は含みません。", "hint"));
  if (result.snapStart > 5000 || result.snapEnd > 5000) box.append(p(`出発地・目的地から最寄りの道路まで ${fmtKm(result.snapStart)}・${fmtKm(result.snapEnd)} あります（距離に含みません）。`, "hint"));
  const ol = document.createElement("ol"); ol.className = "steps";
  for (const s of result.steps) {
    const li = document.createElement("li");
    li.textContent = `${s.name ? `${s.name}（${KIND_JA[s.kind] ?? s.kind}）` : KIND_JA[s.kind] ?? s.kind} ${fmtKm(s.meters)}`;
    ol.append(li);
  }
  box.append(ol);
  const xs = result.coords.map((c) => c[0]), ys = result.coords.map((c) => c[1]);
  setView(fitView([Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)], size.width, size.height, 40));
}

$("route-go").addEventListener("click", () => {
  if (!ends.from || !ends.to) { showRoute({ error: "出発地と目的地を選んでください。" }); return; }
  if (!roads) { showRoute({ error: "先に道路データを取得してください（下のボタン）。経路の計算そのものは端末内で行います。" }); return; }
  showRoute(route(roads, [ends.from.lon, ends.from.lat], [ends.to.lon, ends.to.lat], { avoidFerries: $("avoid-ferries").checked }));
});
$("route-clear").addEventListener("click", () => { ends.from = ends.to = null; $("from").value = $("to").value = ""; routePath = null; $("route-result").replaceChildren(); setPicking(null); invalidate(); });

function showRoadState(has) { $("roads-get").hidden = has; $("roads-forget").hidden = !has; }
