// Maps UI: a world map that works offline on this device. Drag to pan, wheel
// or pinch to zoom, tap a country to see its name and ISO codes, search by
// name or code. The only network use is the consented detail download.
import { createClientConsentHost } from "./kotoba-client-runtime.js";
import { basemapProblems, countryAt, fitView, focusBBox, panBy, screenToWorld, searchCountries, unproject, zoomAt, clampView } from "./geo.js";
import { buildPaths, draw, readColors } from "./map.js";
import { openStore } from "./store.js";
import { createDetailSource } from "./detail.js";
// Generated by scripts/build.mjs from descriptor.json and data/world-110m.json,
// so the page needs no fetch, not even from its own origin.
import descriptor from "./descriptor.js";
import base from "./basemap.js";

const $ = (id) => document.getElementById(id);
const canvas = $("map");
const ctx = canvas.getContext("2d");
const store = openStore();
if (basemapProblems(base).length) throw new Error("bundled basemap is invalid");

let map = base, paths = buildPaths(map), colors = readColors(document.documentElement);
let size = { width: 1, height: 1, dpr: 1 };
let view = null, selected = null, frame = 0;

const invalidate = () => { if (!frame) frame = requestAnimationFrame(() => { frame = 0; draw(ctx, size, view, paths, colors, selected?.a3); }); };
let saveTimer = 0;
const setView = (next) => {
  view = next; invalidate();
  clearTimeout(saveTimer);
  saveTimer = setTimeout(() => store.set("view", view), 400);
};
const worldView = () => fitView([-180, -60, 180, 80], size.width, size.height, 8);

function resize() {
  const rect = canvas.getBoundingClientRect();
  const dpr = Math.min(globalThis.devicePixelRatio || 1, 3);
  size = { width: Math.max(1, rect.width), height: Math.max(1, rect.height), dpr };
  canvas.width = Math.round(size.width * dpr);
  canvas.height = Math.round(size.height * dpr);
  view = view ? clampView(view, size.height) : worldView();
  invalidate();
}
new ResizeObserver(resize).observe(canvas);
matchMedia("(prefers-color-scheme: dark)").addEventListener("change", () => { colors = readColors(document.documentElement); invalidate(); });

// ── selection panel ──────────────────────────────────────────────────────────
function select(country) {
  selected = country;
  const box = $("country");
  box.replaceChildren();
  if (!country) {
    const p = document.createElement("p"); p.className = "muted"; p.textContent = "国をタップすると、名前と ISO コードを表示します。";
    box.append(p);
  } else {
    const h = document.createElement("h2"); h.textContent = country.ja ?? country.name;
    const dl = document.createElement("dl");
    for (const [k, v] of [["英語名", country.name], ["ISO 3166-1 alpha-2", country.a2 ?? "—"], ["ISO 3166-1 alpha-3", country.a3], ["大陸", country.continent ?? "—"]]) {
      const dt = document.createElement("dt"); dt.textContent = k;
      const dd = document.createElement("dd"); dd.textContent = v;
      dl.append(dt, dd);
    }
    box.append(h, dl);
  }
  invalidate();
}
const focus = (country) => { select(country); setView(fitView(focusBBox(country, map.scale), size.width, size.height, 32)); };

// ── pointer, wheel and keyboard input ────────────────────────────────────────
const pointers = new Map();
let gesture = null; // { moved, startX, startY, dist, mid }
const local = (e) => { const r = canvas.getBoundingClientRect(); return [e.clientX - r.left, e.clientY - r.top]; };
const pair = () => { const [a, b] = [...pointers.values()]; return { dist: Math.hypot(a[0] - b[0], a[1] - b[1]), mid: [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2] }; };

canvas.addEventListener("pointerdown", (e) => {
  canvas.setPointerCapture(e.pointerId);
  pointers.set(e.pointerId, local(e));
  const [x, y] = local(e);
  gesture = pointers.size === 2 ? { moved: true, ...pair() } : { moved: false, startX: x, startY: y, last: [x, y] };
});
canvas.addEventListener("pointermove", (e) => {
  if (!pointers.has(e.pointerId) || !gesture) return;
  pointers.set(e.pointerId, local(e));
  if (pointers.size >= 2) {
    const now = pair();
    let next = zoomAt(view, size.width, size.height, now.mid[0], now.mid[1], now.dist / (gesture.dist || now.dist));
    next = panBy(next, size.height, now.mid[0] - gesture.mid[0], now.mid[1] - gesture.mid[1]);
    gesture = { moved: true, ...now };
    setView(next);
    return;
  }
  const [x, y] = local(e);
  if (!gesture.moved && Math.hypot(x - gesture.startX, y - gesture.startY) > 6) gesture.moved = true;
  if (gesture.moved && gesture.last) { setView(panBy(view, size.height, x - gesture.last[0], y - gesture.last[1])); }
  gesture.last = [x, y];
});
const endPointer = (e, cancelled) => {
  if (!pointers.has(e.pointerId)) return;
  pointers.delete(e.pointerId);
  if (!cancelled && gesture && !gesture.moved && pointers.size === 0) {
    const [x, y] = local(e);
    const [lon, lat] = unproject(...screenToWorld(view, size.width, size.height, x, y));
    select(countryAt(map, lon, lat));
  }
  if (pointers.size === 1) { const [p] = pointers.values(); gesture = { moved: true, last: p }; }
  else if (pointers.size === 0) gesture = null;
};
canvas.addEventListener("pointerup", (e) => endPointer(e, false));
canvas.addEventListener("pointercancel", (e) => endPointer(e, true));
canvas.addEventListener("wheel", (e) => {
  e.preventDefault();
  const [x, y] = local(e);
  const delta = e.deltaMode === 1 ? e.deltaY * 16 : e.deltaY;
  setView(zoomAt(view, size.width, size.height, x, y, Math.exp(-delta * 0.0015)));
}, { passive: false });
canvas.addEventListener("dblclick", (e) => { const [x, y] = local(e); setView(zoomAt(view, size.width, size.height, x, y, 2)); });
canvas.addEventListener("keydown", (e) => {
  const step = 80, c = [size.width / 2, size.height / 2];
  const actions = {
    ArrowLeft: () => panBy(view, size.height, step, 0), ArrowRight: () => panBy(view, size.height, -step, 0),
    ArrowUp: () => panBy(view, size.height, 0, step), ArrowDown: () => panBy(view, size.height, 0, -step),
    "+": () => zoomAt(view, size.width, size.height, ...c, 1.5), "=": () => zoomAt(view, size.width, size.height, ...c, 1.5),
    "-": () => zoomAt(view, size.width, size.height, ...c, 1 / 1.5), "0": worldView,
  };
  if (actions[e.key]) { e.preventDefault(); setView(actions[e.key]()); }
});
$("zoom-in").addEventListener("click", () => setView(zoomAt(view, size.width, size.height, size.width / 2, size.height / 2, 2)));
$("zoom-out").addEventListener("click", () => setView(zoomAt(view, size.width, size.height, size.width / 2, size.height / 2, 0.5)));
$("zoom-world").addEventListener("click", () => setView(worldView()));

// ── search ───────────────────────────────────────────────────────────────────
const search = $("search"), results = $("results");
let hits = [], active = -1;
function showResults() {
  results.replaceChildren(...hits.map((c, i) => {
    const li = document.createElement("li");
    li.setAttribute("role", "option"); li.setAttribute("aria-selected", String(i === active));
    const name = document.createElement("span"); name.textContent = c.ja ? `${c.ja}（${c.name}）` : c.name;
    const iso = document.createElement("span"); iso.className = "muted"; iso.textContent = c.a3;
    li.append(name, iso);
    li.addEventListener("pointerdown", (e) => { e.preventDefault(); choose(c); });
    return li;
  }));
  results.hidden = hits.length === 0;
}
function choose(country) { search.value = country.ja ?? country.name; hits = []; showResults(); focus(country); canvas.focus(); }
search.addEventListener("input", () => { hits = searchCountries(map, search.value); active = hits.length ? 0 : -1; showResults(); });
search.addEventListener("keydown", (e) => {
  if (e.key === "ArrowDown" || e.key === "ArrowUp") { e.preventDefault(); if (hits.length) { active = (active + (e.key === "ArrowDown" ? 1 : hits.length - 1)) % hits.length; showResults(); } }
  else if (e.key === "Enter" && hits[active]) { e.preventDefault(); choose(hits[active]); }
  else if (e.key === "Escape") { hits = []; showResults(); }
});
search.addEventListener("blur", () => { hits = []; showResults(); });

// ── detail data (the only external operation) ────────────────────────────────
const detail = createDetailSource({ descriptor, store, consentHost: createClientConsentHost() });
const status = (text, error = false) => { const el = $("detail-status"); el.textContent = text; el.classList.toggle("error", error); };
function useMap(next, label) {
  const a3 = selected?.a3;
  map = next; paths = buildPaths(map);
  $("source").textContent = label;
  if (a3) select(map.countries.find((c) => c.a3 === a3) ?? null); else invalidate();
}
function showDetailState(hasDetail) {
  $("detail-get").hidden = hasDetail;
  $("detail-forget").hidden = !hasDetail;
}
$("detail-get").addEventListener("click", async () => {
  const button = $("detail-get");
  button.disabled = true;
  status("取得するか確認しています…");
  try {
    const { map: next, kept } = await detail.download();
    useMap(next, "Natural Earth 1:50m");
    showDetailState(true);
    status(kept ? "取得して SHA-256 を確認し、端末に保存しました。" : "取得して確認しましたが、端末に保存できませんでした（次回は再取得が必要です）。");
  } catch (error) {
    status(/not approved/.test(error.message) ? "取得しませんでした（通信はしていません）。" : `取得できませんでした: ${error.message}`, !/not approved/.test(error.message));
  } finally { button.disabled = false; }
});
$("detail-forget").addEventListener("click", async () => {
  await detail.forget();
  useMap(base, "Natural Earth 1:110m");
  showDetailState(false);
  status("詳細データを端末から削除しました。");
});

// ── start ────────────────────────────────────────────────────────────────────
resize();
const savedView = await store.get("view");
if (savedView && [savedView.x, savedView.y, savedView.z].every(Number.isFinite)) setView(clampView(savedView, size.height));
const saved = await detail.loadSaved();
if (saved) { useMap(saved, "Natural Earth 1:50m"); showDetailState(true); }

